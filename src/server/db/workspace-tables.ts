import { writeFileSync } from 'node:fs';
import type { Client, Row } from '@libsql/client';
import { identifier, migrateWorkspace, readMigrated } from './fk-rules.ts';
import { WORKSPACE_MIGRATIONS } from './workspace-migrations.ts';

export const WORKSPACE_TABLES_FILE = './src/server/db/schema/workspace.generated.ts';

/** The drizzle column builder for each declared SQLite type the workspace schema uses. */
const BUILDERS: Readonly<Record<string, string>> = {
  TEXT: 'text',
  INTEGER: 'integer',
  REAL: 'real',
};

/** `primaryKey` is the position in the primary key from 1, or 0 outside it (table_info `pk`). */
export interface WorkspaceColumn {
  name: string;
  builder: string;
  notNull: boolean;
  primaryKey: number;
  /** The SQL default, already a TypeScript literal. */
  defaultValue: string | null;
}

export type WorkspaceTable = { name: string; columns: readonly WorkspaceColumn[] };

const camel = (name: string) =>
  name.replace(/_([a-z0-9])/g, (_, next: string) => next.toUpperCase());

/** A quoted string or an integer reads the same in SQL and TypeScript; any other default fails. */
function literal(value: Row[string], column: string): string | null {
  if (value === null) return null;
  if (/^('[^'\\\r\n]*'|-?\d+)$/.test(String(value))) return String(value);
  throw new Error(`${column} has a default the table generator cannot render: ${value}`);
}

/**
 * Every workspace table's columns, sorted by table then column order. pragma_table_list types
 * catalog_search `virtual` and its FTS5 tables `shadow`, so `table` leaves them and the views out;
 * schema_migrations belongs to the migration runner.
 */
export async function readWorkspaceTables(client: Client): Promise<WorkspaceTable[]> {
  const { rows } = await client.execute(
    "SELECT t.name AS tbl, p.* FROM pragma_table_list AS t JOIN pragma_table_info(t.name) AS p WHERE t.schema = 'main' AND t.type = 'table' AND t.name NOT LIKE 'sqlite_%' AND t.name != 'schema_migrations' ORDER BY t.name, p.cid",
  );
  return [...Map.groupBy(rows, (row) => identifier(row.tbl))].map(([table, columns]) => ({
    name: table,
    columns: columns.map((row): WorkspaceColumn => {
      const name = identifier(row.name);
      const builder = BUILDERS[String(row.type).toUpperCase()];
      if (!builder)
        throw new Error(`${table}.${name} has a type the table generator cannot render`);
      const defaultValue = literal(row.dflt_value, `${table}.${name}`);
      return {
        name,
        builder,
        notNull: row.notnull === 1,
        primaryKey: Number(row.pk),
        defaultValue,
      };
    }),
  }));
}

/** The tables file text, already in Biome's format so `npm run check` passes on it. */
export function renderWorkspaceTables(tables: readonly WorkspaceTable[]): string {
  const imports = new Set(['sqliteTable']);
  const definitions = tables.flatMap(({ name, columns }) => {
    const key = columns.filter((c) => c.primaryKey).sort((a, b) => a.primaryKey - b.primaryKey);
    const composite = key.length > 1;
    const lines = columns.map((column) => {
      imports.add(column.builder);
      const primary = !composite && column.primaryKey ? '.primaryKey()' : '';
      const notNull = column.notNull ? '.notNull()' : '';
      const dflt = column.defaultValue === null ? '' : `.default(${column.defaultValue})`;
      return `${camel(column.name)}: ${column.builder}('${column.name}')${primary}${notNull}${dflt},`;
    });
    const head = `export const ${camel(name)} = sqliteTable(`;
    if (!composite) return [`${head}'${name}', {`, ...lines.map((l) => `  ${l}`), '});', ''];
    imports.add('primaryKey');
    const primaryKey = `primaryKey({ columns: [${key.map((c) => `table.${camel(c.name)}`).join(', ')}] })`;
    const line = `  (table) => [${primaryKey}],`;
    const config = line.length <= 100 ? [line] : ['  (table) => [', `    ${primaryKey},`, '  ],'];
    const body = lines.map((l) => `    ${l}`);
    return [head, `  '${name}',`, '  {', ...body, '  },', ...config, ');', ''];
  });
  const byName = tables.map(({ name }) =>
    camel(name) === name ? `  ${name},` : `  ${name}: ${camel(name)},`,
  );
  return [
    '// Generated by `npm run db:workspace-tables` from PRAGMA table_info on the migrated workspace',
    '// schema (docs/CONTRACT.md §4.2, §4.3). Do not edit: tests/integration/workspace-tables.test.ts',
    '// fails when this file differs from a fresh generation. Columns carry their SQL names, types,',
    '// NOT NULL, defaults and primary keys. Checks, indexes, views and catalog_search stay in the',
    '// migrations, and IntegrityGuard reads foreign keys from ../fk-rules.generated.ts.',
    `import { ${[...imports].sort().join(', ')} } from 'drizzle-orm/sqlite-core';`,
    '',
    ...definitions,
    '/** Every workspace table, keyed by its SQL name. */',
    'export const WORKSPACE_TABLES = {',
    ...byName,
    '};',
    '',
  ].join('\n');
}

/** Migrates an in-memory workspace database from `migrations` and renders its tables. */
export async function generateWorkspaceTables(migrations = WORKSPACE_MIGRATIONS): Promise<string> {
  return renderWorkspaceTables(
    await readMigrated(migrateWorkspace(migrations), readWorkspaceTables),
  );
}

if (import.meta.main) {
  writeFileSync(WORKSPACE_TABLES_FILE, await generateWorkspaceTables());
  console.log(`Wrote ${WORKSPACE_TABLES_FILE}`);
}
