import { writeFileSync } from 'node:fs';
import { type Client, createClient, type Row } from '@libsql/client';
import { drizzle } from 'drizzle-orm/libsql';
import { migrate } from 'drizzle-orm/libsql/migrator';
import {
  applyWorkspaceMigrations,
  RUNTIME_MIGRATIONS,
  readWorkspaceMigrations,
  WORKSPACE_MIGRATIONS,
} from './workspace-migrations.ts';

export const FK_RULES_FILE = './src/server/db/fk-rules.generated.ts';
export const CONTROL_MIGRATIONS = './src/server/db/migrations/control';

/** The actions `PRAGMA foreign_key_list` reports in `on_delete` and `on_update`. */
const FOREIGN_KEY_ACTIONS = [
  'NO ACTION',
  'RESTRICT',
  'SET NULL',
  'SET DEFAULT',
  'CASCADE',
] as const;
export type ForeignKeyAction = (typeof FOREIGN_KEY_ACTIONS)[number];

/**
 * One declared foreign key. A composite key is one rule, with `columns[i]` referencing
 * `parentColumns[i]`.
 */
export interface ForeignKeyRule {
  table: string;
  columns: readonly string[];
  parentTable: string;
  parentColumns: readonly string[];
  onDelete: ForeignKeyAction;
  onUpdate: ForeignKeyAction;
}

/** Rules per database (CONTRACT §4.4): `runtime` is melos-agent-runtime's runner tables. */
export type ForeignKeyDatabase = 'control' | 'workspace' | 'runtime';
export type ForeignKeyRules = Readonly<Record<ForeignKeyDatabase, readonly ForeignKeyRule[]>>;

/** Generated code interpolates these names into SQL and TypeScript, so anything else fails. */
export function identifier(value: Row[string]): string {
  if (typeof value === 'string' && /^[A-Za-z_][A-Za-z0-9_]*$/.test(value)) return value;
  throw new Error(`Generated schema code needs plain identifiers, got ${String(value)}`);
}

function action(value: Row[string]): ForeignKeyAction {
  const known = FOREIGN_KEY_ACTIONS.find((candidate) => candidate === value);
  if (!known) throw new Error(`Unknown foreign-key action ${String(value)}`);
  return known;
}

const compare = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

/** Every foreign key SQLite built in a migrated database, sorted by child then parent columns. */
export async function readForeignKeyRules(client: Client): Promise<ForeignKeyRule[]> {
  // pragma_foreign_key_list(name) is PRAGMA foreign_key_list(<table>) for every table in
  // sqlite_master: columns id, seq, table, from, to, on_update, on_delete, match (§4.4).
  const { rows } = await client.execute(
    "SELECT m.name AS child, f.* FROM sqlite_master AS m JOIN pragma_foreign_key_list(m.name) AS f WHERE m.type = 'table' ORDER BY m.name, f.id, f.seq",
  );
  // A composite key is several rows sharing one id within its table, ordered by seq.
  const keys = Map.groupBy(rows, (row) => `${row.child} ${row.id}`);
  return [...keys.values()]
    .map((key): ForeignKeyRule => {
      if (key.some((row) => row.to === null)) {
        throw new Error(`${key[0].child} references ${key[0].table} without naming its columns`);
      }
      return {
        table: identifier(key[0].child),
        columns: key.map((row) => identifier(row.from)),
        parentTable: identifier(key[0].table),
        parentColumns: key.map((row) => identifier(row.to)),
        onDelete: action(key[0].on_delete),
        onUpdate: action(key[0].on_update),
      };
    })
    .sort(
      (a, b) =>
        compare(a.table, b.table) ||
        compare(a.columns.join(), b.columns.join()) ||
        compare(a.parentTable, b.parentTable) ||
        compare(a.parentColumns.join(), b.parentColumns.join()),
    );
}

/** The rules file text, already in Biome's format so `npm run check` passes on it. */
export function renderForeignKeyRules(rules: ForeignKeyRules): string {
  const list = (names: readonly string[]) => `[${names.map((name) => `'${name}'`).join(', ')}]`;
  const databases = Object.entries(rules).flatMap(([database, databaseRules]) => [
    `  ${database}: [`,
    ...databaseRules.flatMap((rule) => [
      '    {',
      `      table: '${rule.table}',`,
      `      columns: ${list(rule.columns)},`,
      `      parentTable: '${rule.parentTable}',`,
      `      parentColumns: ${list(rule.parentColumns)},`,
      `      onDelete: '${rule.onDelete}',`,
      `      onUpdate: '${rule.onUpdate}',`,
      '    },',
    ]),
    '  ],',
  ]);
  return [
    '// Generated by `npm run db:fk-rules` from PRAGMA foreign_key_list on the migrated schemas',
    '// (docs/CONTRACT.md §4.4, DAT-001). Do not edit: tests/integration/fk-rules.test.ts fails',
    '// when this file differs from a fresh generation.',
    "import type { ForeignKeyRules } from './fk-rules';",
    '',
    'export const FOREIGN_KEY_RULES: ForeignKeyRules = {',
    ...databases,
    '};',
    '',
  ].join('\n');
}

/**
 * Runs `read` on an empty in-memory libSQL database that `prepare` migrated. In memory because
 * Windows keeps a closed libSQL file locked until the process exits.
 */
export async function readMigrated<T>(
  prepare: (client: Client) => Promise<unknown>,
  read: (client: Client) => Promise<T>,
): Promise<T> {
  const client = createClient({ url: ':memory:' });
  try {
    await prepare(client);
    return await read(client);
  } finally {
    client.close();
  }
}

/** Applies the numbered workspace migrations in `folder`, as provisioning does. */
export const migrateWorkspace = (folder: string) => (client: Client) =>
  applyWorkspaceMigrations(client, { migrations: readWorkspaceMigrations(folder) });

/** Migrates each schema into its own in-memory database and renders the rules of all three. */
export async function generateForeignKeyRules(
  controlMigrations = CONTROL_MIGRATIONS,
  workspaceMigrations = WORKSPACE_MIGRATIONS,
  runtimeMigrations = RUNTIME_MIGRATIONS,
): Promise<string> {
  const migrateControl = (client: Client) =>
    migrate(drizzle(client), { migrationsFolder: controlMigrations });
  return renderForeignKeyRules({
    control: await readMigrated(migrateControl, readForeignKeyRules),
    workspace: await readMigrated(migrateWorkspace(workspaceMigrations), readForeignKeyRules),
    runtime: await readMigrated(migrateWorkspace(runtimeMigrations), readForeignKeyRules),
  });
}

if (import.meta.main) {
  writeFileSync(FK_RULES_FILE, await generateForeignKeyRules());
  console.log(`Wrote ${FK_RULES_FILE}`);
}
