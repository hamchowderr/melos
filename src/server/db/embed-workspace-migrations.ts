import { writeFileSync } from 'node:fs';
import {
  readWorkspaceMigrations,
  WORKSPACE_MIGRATIONS,
  type WorkspaceMigration,
} from './workspace-migrations.ts';

export const EMBEDDED_MIGRATIONS_FILE = './src/server/db/workspace-migrations.generated.ts';

/** A template literal whose value is `text`: backslashes, backticks, `${` and CR are escaped. */
const template = (text: string) =>
  `\`${text.replace(/[`\\]|\$\{|\r/g, (c) => (c === '\r' ? '\\r' : `\\${c}`))}\``;

/** The embedded migrations file text, already in Biome's format so `npm run check` passes on it. */
export function renderEmbeddedMigrations(migrations: readonly WorkspaceMigration[]): string {
  const entries = migrations.flatMap(({ version, name, file, statements }) => [
    '  {',
    `    version: ${version},`,
    `    name: '${name}',`,
    `    file: '${file}',`,
    ...(statements.length === 0
      ? ['    statements: [],']
      : ['    statements: [', ...statements.map((s) => `      ${template(s)},`), '    ],']),
    '  },',
  ]);
  return [
    '// Generated by `npm run db:workspace-migrations` from the numbered SQL files in',
    '// src/server/db/migrations/workspace (docs/CONTRACT.md §4.2, §7.2). Do not edit:',
    '// tests/integration/workspace-migrations.test.ts fails when this file differs from a fresh',
    '// generation. Provisioning and MigrationRunner apply this list, so a deployed function never',
    '// reads the SQL folder, which its bundle does not include.',
    "import type { WorkspaceMigration } from './workspace-migrations';",
    '',
    'export const EMBEDDED_WORKSPACE_MIGRATIONS: readonly WorkspaceMigration[] = [',
    ...entries,
    '];',
    '',
  ].join('\n');
}

/** Reads `folder`, refusing a misnamed file, a duplicate or a gap, and renders its migrations. */
export function generateEmbeddedMigrations(folder = WORKSPACE_MIGRATIONS): string {
  return renderEmbeddedMigrations(readWorkspaceMigrations(folder));
}

if (import.meta.main) {
  writeFileSync(EMBEDDED_MIGRATIONS_FILE, generateEmbeddedMigrations());
  console.log(`Wrote ${EMBEDDED_MIGRATIONS_FILE}`);
}
