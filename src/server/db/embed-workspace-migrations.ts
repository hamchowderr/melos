import { writeFileSync } from 'node:fs';
import {
  RUNTIME_MIGRATIONS,
  readWorkspaceMigrations,
  WORKSPACE_MIGRATIONS,
  type WorkspaceMigration,
} from './workspace-migrations.ts';

export const EMBEDDED_MIGRATIONS_FILE = './src/server/db/workspace-migrations.generated.ts';
export const EMBEDDED_RUNTIME_MIGRATIONS_FILE = './src/server/db/runtime-migrations.generated.ts';

/** One embedded migrations module: where its SQL lives and the header that says who applies it. */
export interface EmbedTarget {
  folder: string;
  file: string;
  exportName: string;
  header: readonly string[];
}

export const WORKSPACE_EMBED: EmbedTarget = {
  folder: WORKSPACE_MIGRATIONS,
  file: EMBEDDED_MIGRATIONS_FILE,
  exportName: 'EMBEDDED_WORKSPACE_MIGRATIONS',
  header: [
    '// Generated by `npm run db:workspace-migrations` from the numbered SQL files in',
    '// src/server/db/migrations/workspace (docs/CONTRACT.md §4.2, §7.2). Do not edit:',
    '// tests/integration/workspace-migrations.test.ts fails when this file differs from a fresh',
    '// generation. Provisioning and MigrationRunner apply this list, so a deployed function never',
    '// reads the SQL folder, which its bundle does not include.',
  ],
};

export const RUNTIME_EMBED: EmbedTarget = {
  folder: RUNTIME_MIGRATIONS,
  file: EMBEDDED_RUNTIME_MIGRATIONS_FILE,
  exportName: 'EMBEDDED_RUNTIME_MIGRATIONS',
  header: [
    '// Generated by `npm run db:workspace-migrations` from the numbered SQL files in',
    '// src/server/db/migrations/runtime (docs/CONTRACT.md §4.1, §7.9). Do not edit:',
    '// tests/integration/runtime-database.test.ts fails when this file differs from a fresh',
    '// generation. The runtime database client applies this list on first use.',
  ],
};

/** A template literal whose value is `text`: backslashes, backticks, `${` and CR are escaped. */
const template = (text: string) =>
  `\`${text.replace(/[`\\]|\$\{|\r/g, (c) => (c === '\r' ? '\\r' : `\\${c}`))}\``;

/** The embedded migrations file text, already in Biome's format so `npm run check` passes on it. */
export function renderEmbeddedMigrations(
  migrations: readonly WorkspaceMigration[],
  target: EmbedTarget = WORKSPACE_EMBED,
): string {
  const entries = migrations.flatMap(({ version, name, file, statements }) => [
    '  {',
    `    version: ${version},`,
    `    name: '${name}',`,
    `    file: '${file}',`,
    ...(statements.length === 0
      ? ['    statements: [],']
      : ['    statements: [', ...statements.map((s) => `      ${template(s)},`), '    ],']),
    '  },',
  ]);
  return [
    ...target.header,
    "import type { WorkspaceMigration } from './workspace-migrations';",
    '',
    `export const ${target.exportName}: readonly WorkspaceMigration[] = [`,
    ...entries,
    '];',
    '',
  ].join('\n');
}

/** Reads `folder`, refusing a misnamed file, a duplicate or a gap, and renders its migrations. */
export function generateEmbeddedMigrations(
  folder = WORKSPACE_MIGRATIONS,
  target: EmbedTarget = WORKSPACE_EMBED,
): string {
  return renderEmbeddedMigrations(readWorkspaceMigrations(folder), target);
}

if (import.meta.main) {
  for (const target of [WORKSPACE_EMBED, RUNTIME_EMBED]) {
    writeFileSync(target.file, generateEmbeddedMigrations(target.folder, target));
    console.log(`Wrote ${target.file}`);
  }
}
